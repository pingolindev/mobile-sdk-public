# Regenerate THIRD_PARTY_LICENSES.md — the third-party licence inventory for
# every Rust crate compiled into this repo's libraries.
#
# Requires cargo-about:  cargo install cargo-about
#
# Why this is a script rather than a single cargo-about invocation: crates/mobile-sdk
# is excluded from the workspace (its bundled-sqlite stack conflicts with the
# workspace's linking — see the root Cargo.toml), so cargo cannot resolve one
# dependency graph covering both it and the workspace members. Each half is
# generated separately, against the shared about.toml, and concatenated here.
#
# The command fails if any dependency carries a licence not listed in
# about.toml's `accepted` — which is the point: a new licence should be a
# decision, not a silent addition to a notice file.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

OUT="THIRD_PARTY_LICENSES.md"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

command -v cargo-about >/dev/null 2>&1 \
    || { echo "error: cargo-about not found. Install it with: cargo install cargo-about" >&2; exit 1; }

echo "==> crates/mobile-sdk (libpingolin_mobile)"
cargo about generate \
    --config about.toml \
    --manifest-path crates/mobile-sdk/Cargo.toml \
    --output-file "$TMP/mobile-sdk.md" \
    about.hbs

echo "==> workspace (note-collab-sdk, track-proto)"
cargo about generate \
    --config about.toml \
    --manifest-path Cargo.toml \
    --output-file "$TMP/workspace.md" \
    about.hbs

echo "==> writing $OUT"
{
    cat <<'EOF'
# Third-party licences

This file is generated by [cargo-about](https://github.com/EmbarkStudios/cargo-about)
from the dependency graphs in `Cargo.lock`. Do not edit it by hand — run
`./generate-licenses.sh` instead, and see `about.toml` for the configuration.

It lists every third-party Rust crate compiled into this repo's libraries,
grouped by licence, with the full text of each licence. Pingolin's own code is
licensed separately; see [LICENSE](LICENSE).

The two sections below correspond to the two dependency graphs in this repo:
`crates/mobile-sdk` is excluded from the cargo workspace, so it resolves its
dependencies independently of the workspace members. Crates used by both appear
in both sections.

## What this list covers

Attribution obligations attach to what is **redistributed**, so the scope is
the crates whose code ends up in the built libraries, resolved for every target
in `about.toml` and unioned — a crate pulled in on one platform only would
otherwise go unreported.

- **Development dependencies are excluded.** They build and run the tests and
  are never distributed.
- **Build-only dependencies are excluded.** They run inside the compiler and
  contribute no code to the libraries.
- **Procedural-macro crates are included.** They also run only inside the
  compiler and arguably need no notice, but `cargo-about` cannot distinguish
  them from ordinary dependencies. They are listed rather than guessed at:
  over-attribution is harmless, a missing attribution is not.

The Android apps ship their own inventories covering the same `.so` files.
Those answer a narrower question — what is linked into the APK a user installs
— and therefore drop proc-macro crates as well, which is why their crate count
is lower than this one. The difference is deliberate, not a disagreement.

## crates/mobile-sdk — libpingolin_mobile.so / PingolinMobile.xcframework

EOF
    cat "$TMP/mobile-sdk.md"
    cat <<'EOF'

## Workspace — note-collab-sdk (libnote_collab_sdk.so) and track-proto

EOF
    cat "$TMP/workspace.md"
} >"$OUT"

echo "==> done: $OUT ($(wc -l <"$OUT") lines)"
